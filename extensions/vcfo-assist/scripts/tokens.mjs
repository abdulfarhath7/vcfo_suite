#!/usr/bin/env node
/**
 * Writes the side panel's VCFO Spectrum tokens (src/ui/spectrum-tokens.css) from the Suite's
 * source of truth, docs/design/design-tokens.json. Every colour becomes a CSS custom property with
 * its light value on :root and its dark value under prefers-color-scheme: dark; spacing, radius,
 * size, border width, shadow and type tokens follow. Hex is the design value, so hex is written.
 *
 *   node scripts/tokens.mjs           write the file
 *   node scripts/tokens.mjs --check   exit 1 when the file no longer matches the JSON
 *
 * src/ui/spectrum-tokens.test.ts runs the same check in `npm test`, so a token change in Suite
 * fails the extension's tests until this script is run again.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const TOKENS_JSON = path.resolve(here, '../../../docs/design/design-tokens.json');
export const TOKENS_CSS = path.resolve(here, '../src/ui/spectrum-tokens.css');

/* R-28: the app maps weight 600 (Tailwind `semibold`) to 500, so the panel loads only 400, 500
   and 700 (UI) and 500 (mono). The type styles below follow the same mapping. */
const WEIGHT = (w) => (w === 600 ? 500 : w);

/** `{ink}` aliases another token; anything else is used as it is. */
const value = (v) => (typeof v === 'string' && /^\{[a-z0-9-]+\}$/.test(v) ? `var(--${v.slice(1, -1)})` : String(v));

/** The CSS text for a parsed design-tokens.json. Pure, so the drift test can call it. */
export function renderTokensCss(json) {
  const light = [];
  const dark = [];
  const plain = [];
  for (const t of json.color.tokens) {
    light.push(`  --${t.name}: ${value(t.value.light)};`);
    if (t.value.dark !== t.value.light) dark.push(`    --${t.name}: ${value(t.value.dark)};`);
  }
  for (const t of json.shadow.tokens) {
    if (typeof t.value === 'object') {
      light.push(`  --${t.name}: ${t.value.light};`);
      if (t.value.dark !== t.value.light) dark.push(`    --${t.name}: ${t.value.dark};`);
    } else plain.push(`  --${t.name}: ${t.value};`);
  }
  for (const group of ['spacing', 'radius', 'size', 'borderWidth'])
    for (const t of json[group].tokens) plain.push(`  --${t.name}: ${t.value};`);

  /* Fonts. The app's stacks start with next/font's variables; the panel sets those to the bundled
     faces (fonts.css), so the stack itself is the JSON's, unchanged. */
  const [ui, mono] = [json.type.fonts.find((f) => f.family === 'ui'), json.type.fonts.find((f) => f.family === 'mono')];
  plain.push(`  --font-sans: '${ui.name}';`);
  plain.push(`  --font-mono: '${mono.name}';`);
  plain.push(`  --font-ui: ${json.type.families.ui};`);
  plain.push(`  --font-code: ${json.type.families.mono};`);
  for (const g of json.type.groups)
    for (const s of g.styles) {
      const family = g.family === 'mono' ? 'var(--font-code)' : 'var(--font-ui)';
      plain.push(`  --type-${s.name}: ${WEIGHT(s.fontWeight)} ${s.fontSize}/${s.lineHeight} ${family};`);
      plain.push(`  --type-${s.name}-tracking: ${s.letterSpacing};`);
    }

  return [
    `/* GENERATED by scripts/tokens.mjs from docs/design/design-tokens.json (${json.name} v${json.version}, ${json.generated}).`,
    '   Do not edit by hand: run `node scripts/tokens.mjs`. src/ui/spectrum-tokens.test.ts fails on drift. */',
    ':root {',
    '  color-scheme: light dark;',
    ...light,
    ...plain,
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    '  :root {',
    ...dark,
    '  }',
    '}',
    '',
  ].join('\n');
}

export function expectedCss() {
  return renderTokensCss(JSON.parse(readFileSync(TOKENS_JSON, 'utf8')));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = expectedCss();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(TOKENS_CSS, 'utf8');
    } catch {
      /* missing counts as drift */
    }
    if (current !== css) {
      console.error('src/ui/spectrum-tokens.css is out of date. Run: node scripts/tokens.mjs');
      process.exit(1);
    }
    console.log('spectrum-tokens.css matches design-tokens.json');
  } else {
    writeFileSync(TOKENS_CSS, css);
    console.log(`wrote ${path.relative(process.cwd(), TOKENS_CSS)}`);
  }
}
