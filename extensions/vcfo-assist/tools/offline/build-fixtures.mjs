// Builds the SANITIZED offline fixtures in tools/offline/fixtures/ from the captured MCA schemas
// (portal-data/mca-v3/schemas). Each fixture rebuilds a captured page's AEM structure with the
// real node ids, widget ids, `_jqName` names, labels, option lists, hidden system fields (userId,
// formId, srn) and buttons, and NO value of any kind: nothing typed by anyone is in a schema.
// Dependent lists the capture holds empty get the options the portal would load, so a fill can be
// checked. They stand in for real captures, which never enter git (see tools/offline/README.md).
//
//   node tools/offline/build-fixtures.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const SCHEMAS = path.resolve(here, '../../portal-data/mca-v3/schemas');
const OUT = path.join(here, 'fixtures');
mkdirSync(OUT, { recursive: true });
const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const LOADED = {
  'class-of-company': ['Private', 'Public'],
  'category-of-company': ['Company limited by shares', 'Company limited by guarantee', 'Unlimited company'],
  'subcategory-of-company': ['Indian non-government company', 'Union government company', 'State government company'],
  Area1: ['Banjara Hills', 'Gachibowli', 'Madhapur'],
  facorrespondenceaddress_proposedCompanyRegistered: ['Registrar of Companies, Hyderabad', 'Registrar of Companies, Delhi'],
};
/** System fields MCA keeps hidden in the form; a fixture keeps them hidden too. */
const HIDDEN = /^(formId|formDescription|formName|formVersion|userId|integrationId|referenceNumber|srn|srNumber|Path_for_PDFGeneration|formIntegrationId|formAttachList|formAttachmentHidden|prefill|prefillStatus|flag[A-Z]|hidden-|action|operation|linkage|fourthFieldValue|CIN$|SRFOStatus|serveAction|lastUpdatedDate|parent_ID|maskFlag|verifyOTPcheck|mobileOTPValidated12|emailOTPValidated12|prefillFlag|directorAPIResponse|panHidden|saveFlag)/;

function control(f) {
  const w = f.widget ?? {};
  const id = w.id ?? `${f.id}_widget`;
  const name = w.name ?? `${f.id}_jqName`;
  if (f.type === 'guideDropDownList') {
    const loaded = LOADED[f.key] ?? LOADED[f.semantic?.[0]];
    const opts = loaded ? [{ v: '', t: 'Select Here' }, ...loaded.map((t) => ({ v: t, t }))] : (w.options ?? []);
    return `<select id="${esc(id)}" name="${esc(name)}">${opts.map((o) => `<option value="${esc(o.v)}">${esc(o.t)}</option>`).join('')}</select>`;
  }
  if (f.type === 'guideCheckBox' && w.type === 'radio') {
    return ['Yes', 'No'].map((v, i) => `<label><input type="radio" id="${esc(id)}-${i}" name="${esc(name)}" value="${v}"> ${v}</label>`).join(' ');
  }
  if (f.type === 'guideCheckBox' || f.type === 'guideCheckBoxGroup') return `<input type="checkbox" id="${esc(id)}" name="${esc(name)}">`;
  if (f.type === 'guideFileUpload') return `<input type="file" id="${esc(id)}" name="${esc(name)}">`;
  if (f.type === 'guidePasswordBox') return `<input type="password" id="${esc(id)}" name="${esc(name)}">`;
  const max = w.maxlength ? ` maxlength="${esc(w.maxlength)}"` : '';
  const ph = w.placeholder ? ` placeholder="${esc(w.placeholder)}"` : '';
  return `<input type="${w.type === 'email' ? 'email' : 'text'}" id="${esc(id)}" name="${esc(name)}"${max}${ph}>`;
}

function render(f) {
  if (f.type === 'guideButton') return '';
  const hidden = HIDDEN.test(f.key) ? ' style="display:none"' : '';
  const label = (f.label ?? '').trim();
  return `<div class="guideFieldNode ${esc(f.type)} ${esc((f.semantic ?? [f.key]).join(' '))}" id="${esc(f.id)}"${hidden}${f.mandatory ? ' data-mandatory="true"' : ''}>
  <div class="guideFieldLabel"><label for="${esc(f.widget?.id ?? `${f.id}_widget`)}">${esc(label)}</label></div>
  <div class="guideFieldWidget">${control(f)}</div>
</div>`;
}

function fixture(form, keep) {
  const raw = JSON.parse(readFileSync(path.join(SCHEMAS, `${form}.json`), 'utf8'));
  const fields = raw.fields.filter((f) => !keep || keep(f));
  const buttons = (raw.buttons ?? []).filter((b) => b.text && (!keep || /Save|Submit|Auto check|Download PDF|Send OTP|Verify OTP|OK|Next|Pay/.test(b.text)));
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="vcfo-capture-url" content="${esc(raw.url)}">
<title>FIXTURE ${esc(form)} (sanitized, rebuilt from the captured schema)</title>
</head>
<body>
<!-- GENERATED by tools/offline/build-fixtures.mjs from portal-data/mca-v3/schemas/${esc(form)}.json.
     Structure only: no value typed by any person. Not the live MCA page. -->
<div class="modal"><button type="button" id="okInfoModalBtn">OK</button></div>
<div id="guideContainer-rootPanel__" class="guideRootPanel">
${fields.map(render).filter(Boolean).join('\n')}
<div class="buttons">
${buttons.map((b) => `<button type="button" id="${esc(b.id)}">${esc(b.text)}</button>`).join('\n')}
</div>
</div>
</body>
</html>
`;
  writeFileSync(path.join(OUT, `${form}.html`), html);
  return fields.length;
}

const recipeKeys = (id) => {
  const r = JSON.parse(readFileSync(path.resolve(here, `../../../../src/lib/assist-agents/recipes/${id}.json`), 'utf8'));
  return new Set(r.fields.map((f) => /^\.guideFieldNode\.(.+)$/.exec(f.css ?? '')?.[1]).filter(Boolean));
};
const partB = recipeKeys('spice-b');
