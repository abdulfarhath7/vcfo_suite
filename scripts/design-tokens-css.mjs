// Emits the token block of app/globals.css from docs/design/design-tokens.json.
//   node scripts/design-tokens-css.mjs            # print the block
//   node scripts/design-tokens-css.mjs --write    # replace the block between the markers in app/globals.css
// Colour tokens are OKLCH channel triplets, read as oklch(var(--token) / <alpha-value>) in
// tailwind.config.ts. The legacy aliases at the end keep old names resolving until 2026-11-30.
import { readFileSync, writeFileSync } from 'node:fs';
