const END = '  /* @design-tokens:end */';

const value = (t, mode) => {
  const v = t.value[mode];
  const alias = /^\{(.+)\}$/.exec(v);
  if (alias) return `var(--${alias[1]})`;
  if (t.oklch) return t.oklch[mode];
  return v; // rgba() scrim and shadow strings are used as plain var()
};

const lines = (mode) => tokens.color.tokens.map((t) => `    --${t.name}: ${value(t, mode)};`);
const shadows = (mode) => tokens.shadow.tokens.map((t) => `    --${t.name}: ${t.value[mode]};`);

