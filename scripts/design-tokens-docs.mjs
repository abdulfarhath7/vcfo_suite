// Emits src/lib/doc-style/spectrum-tokens.ts from docs/design/design-tokens.json, so the
// generated documents (Word and PDF) read the Spectrum palette instead of hard-coding colours.
//   node scripts/design-tokens-docs.mjs            # print the file
//   node scripts/design-tokens-docs.mjs --write    # write src/lib/doc-style/spectrum-tokens.ts
// Documents are printed on white paper, so only the light theme is emitted. Aliases such as
// `rule: {ink}` are resolved; values that are not plain hex (gradients, rgba scrims) are left out.
// src/lib/doc-style/spectrum-tokens.test.ts fails when this file and the JSON drift apart.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(path.join(root, 'docs/design/design-tokens.json'), 'utf8'));
const OUT = path.join(root, 'src/lib/doc-style/spectrum-tokens.ts');

const byName = new Map(tokens.color.tokens.map((t) => [t.name, t]));
function lightHex(t, seen = new Set()) {
  const v = t.value?.light;
  const alias = /^\{(.+)\}$/.exec(v ?? '');
  if (alias) {
    if (seen.has(alias[1])) throw new Error(`alias loop at ${alias[1]}`);
    seen.add(alias[1]);
    return lightHex(byName.get(alias[1]), seen);
  }
  return /^#[0-9a-f]{6}$/i.test(v ?? '') ? v.toLowerCase() : null;
}

const hexLines = tokens.color.tokens
  .map((t) => [t.name, lightHex(t)])
  .filter(([, hex]) => hex)
  .map(([name, hex]) => `  '${name}': '${hex}',`);

const font = (family) => tokens.type.fonts.find((f) => f.family === family)?.name;

const file = [
  '// Generated by scripts/design-tokens-docs.mjs from docs/design/design-tokens.json. Do not edit;',
  '// change the JSON and run `node scripts/design-tokens-docs.mjs --write`.',
  '',
  '/** VCFO Spectrum colours for printed documents: the light theme, as #rrggbb, aliases resolved. */',
  'export const SPECTRUM_HEX = {',
  ...hexLines,
  '} as const;',
  '',
  'export type SpectrumColor = keyof typeof SPECTRUM_HEX;',
  '',
  '/** The Spectrum font families by role: `ui` for all text, `mono` for identifiers only. */',
  'export const SPECTRUM_FONTS = {',
  `  ui: '${font('ui')}',`,
  `  mono: '${font('mono')}',`,
  '} as const;',
  '',
].join('\n');

if (process.argv.includes('--write')) {
  writeFileSync(OUT, file);
  console.log(`wrote ${hexLines.length} colours to ${path.relative(root, OUT)}`);
} else {
  process.stdout.write(file);
}
