#!/usr/bin/env node
/**
 * Client portal CSS scoper (portal redesign, Oct 2026).
 *
 * The client portal is a port of the owner's prototype (sbc-vcfo-local,
 * `source/portal/v4`). Its CSS is copied verbatim into
 * `src/components/portal/css-src/*.css`. Those files use global selectors
 * (`:root`, `html`, `body`, `.btn`, `h2`, ...). This script rewrites every
 * rule so it only applies inside the portal root element (`.cpx`, rendered by
 * `PortalRoot`), which keeps the staff portals untouched.
 *
 *   node scripts/portal-css.mjs        # rebuild css-src → css
 *
 * Mapping:
 *   :root / html / body (+ qualifiers)  → .cpx (+ qualifiers)
 *   :root[data-theme="light"]           → .cpx[data-theme="light"]
 *   anything else                        → .cpx <selector>
 *   @keyframes x                         → @keyframes x-cpx (Tailwind also has `spin`, `pulse`)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
/**
 * Every folder of copied prototype CSS. Both use the same root class: the
 * client portal (`src/components/portal`) and the staff console
 * (`src/components/console`, manager / admin / super admin / developer, which
 * also loads the portal's base sheets). A person only ever mounts one of them.
 */
const FOLDERS = ['src/components/portal', 'src/components/console'].map((d) => ({
  src: path.join(ROOT, d, 'css-src'),
  out: path.join(ROOT, d, 'css'),
}));
const BASE = '.cpx';
const SUFFIX = '-cpx';

function splitTop(sel) {
  const out = [];
  let depth = 0;
  let cur = '';
  for (const ch of sel) {
    if (ch === '(' || ch === '[') depth++;
    if (ch === ')' || ch === ']') depth--;
    if (ch === ',' && depth === 0) {
      out.push(cur.trim());
      cur = '';
    } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

function scopeSelector(sel) {
  // attributes the prototype set on <html> / <body> live on the portal root here
  if (/^\[data-(theme|role|seat)/.test(sel)) sel = 'html' + sel;
  const m = sel.match(/^(?::root|html|body)((?:\[[^\]]*\]|\.[\w-]+|:not\((?:[^()]|\([^()]*\))*\)|:has\((?:[^()]|\([^()]*\))*\)|::?(?:before|after))*)(?:\s+body((?:\[[^\]]*\]|\.[\w-]+)*))?(\s*)(.*)$/s);
  if (m) {
    const quals = (m[1] || '') + (m[2] || '');
    const gap = m[3] || '';
    const rest = (m[4] || '').trim();
    const host = `${BASE}${quals}`;
    if (!rest) return host;
    if (!gap && rest.startsWith(':')) return `${host}${rest}`;
    return `${host} ${rest}`;
  }
  return `${BASE} ${sel}`;
}

function processFile(SRC, OUT, file) {
  const raw = fs.readFileSync(path.join(SRC, file), 'utf8');
  const root = postcss.parse(raw, { from: file });
  const names = new Set();
  root.walkAtRules(/keyframes$/, (at) => {
    names.add(at.params.trim());
    at.params = at.params.trim() + SUFFIX;
  });
  root.walkRules((rule) => {
    if (rule.parent && rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
    rule.selector = splitTop(rule.selector).map(scopeSelector).join(',\n');
  });
  if (names.size) {
    const re = new RegExp(`(^|[\\s,])(${[...names].map((n) => n.replace(/[-]/g, '\\-')).join('|')})(?=$|[\\s,;])`, 'g');
    root.walkDecls(/^(animation|animation-name)$/, (d) => {
      d.value = d.value.replace(re, (_, pre, n) => `${pre}${n}${SUFFIX}`);
    });
  }
  const out = `/* GENERATED by scripts/portal-css.mjs from css-src/${file} · do not edit */\n` + root.toString();
  fs.writeFileSync(path.join(OUT, file), out);
  return { file, rules: root.nodes.length, keyframes: names.size };
}

for (const { src: SRC, out: OUT } of FOLDERS) {
  if (!fs.existsSync(SRC)) continue;
  fs.mkdirSync(OUT, { recursive: true });
  for (const f of fs.readdirSync(SRC).filter((f) => f.endsWith('.css')).sort()) {
    const r = processFile(SRC, OUT, f);
    console.log(`${path.relative(ROOT, SRC)}/${r.file} → css/${r.file} (${r.rules} top-level nodes, ${r.keyframes} keyframes)`);
  }
}
