#!/usr/bin/env node
/**
 * Client portal — Tailwind "island" for the shared step form (portal redesign, Oct 2026).
 *
 * The new client portal (`src/components/portal`) runs on the prototype's CSS,
 * scoped under `.cpx`. That CSS styles bare elements (`.cpx button { background:
 * none; padding: 0; font: inherit }`, `.cpx input { font: inherit }` …), and
 * `.cpx button` (0,1,1) out-ranks every Tailwind utility (0,1,0). The shared
 * step form (`MilestoneResponseForm`) and the board-resolution preview are
 * Tailwind components, so inside the portal their buttons and inputs would lose
 * their colours, padding and type.
 *
 * This script re-emits the Tailwind utilities those components use, under an
 * `important` selector (`.sw-tw`), into `css-src/95-incorporation-tw.css`.
 * `node scripts/portal-css.mjs` then scopes it like every portal file, so a rule
 * reads `.cpx .sw-tw .bg-primary` (0,3,0) and wins inside the island only.
 *
 *   node scripts/portal-tw-island.mjs && node scripts/portal-css.mjs
 *
 * Content = the import closure of the entry files, limited to src/components
 * and src/views (where class names live). Preflight is off: the app's global
 * preflight already applies.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';
import tailwindcss from 'tailwindcss';
import loadConfig from 'tailwindcss/loadConfig.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/components/portal/css-src/95-incorporation-tw.css');
const ENTRIES = [
  'src/views/incorporation/MilestoneResponseForm.tsx',
  'src/components/board-resolution/BoardResolutionDocPreview.tsx',
];
const FOLLOW = [path.join(ROOT, 'src/components') + path.sep, path.join(ROOT, 'src/views') + path.sep];

function resolveImport(from, spec) {
  let base;
  if (spec.startsWith('@/')) base = path.join(ROOT, 'src', spec.slice(2));
  else if (spec.startsWith('.')) base = path.resolve(path.dirname(from), spec);
  else return null;
  for (const c of [base, `${base}.tsx`, `${base}.ts`, path.join(base, 'index.tsx'), path.join(base, 'index.ts')]) {
    if (fs.existsSync(c) && fs.statSync(c).isFile()) return c;
  }
  return null;
}

const seen = new Set();
const queue = ENTRIES.map((e) => path.join(ROOT, e));
while (queue.length) {
  const f = queue.pop();
  if (seen.has(f)) continue;
  seen.add(f);
  const src = fs.readFileSync(f, 'utf8');
  for (const m of src.matchAll(/(?:from\s+|import\s+|import\()\s*['"]([^'"]+)['"]/g)) {
    const r = resolveImport(f, m[1]);
    if (r && /\.(tsx|ts)$/.test(r) && !/\.test\.tsx?$/.test(r) && FOLLOW.some((d) => r.startsWith(d))) queue.push(r);
  }
}
const files = [...seen].sort();

const base = loadConfig(path.join(ROOT, 'tailwind.config.ts'));
const config = { ...base, content: files, important: '.sw-tw', corePlugins: { ...(base.corePlugins ?? {}), preflight: false } };
const result = await postcss([tailwindcss(config)]).process('@tailwind utilities;\n', { from: undefined });
const head = `/* GENERATED by scripts/portal-tw-island.mjs from ${files.length} files (${ENTRIES.join(', ')} and their imports) · do not edit.\n   Tailwind utilities under .sw-tw, so the shared step form keeps its look inside the portal. */\n`;
fs.writeFileSync(OUT, head + result.css);
console.log(`${path.relative(ROOT, OUT)}: ${files.length} content files, ${(result.css.length / 1024).toFixed(1)} KB`);
