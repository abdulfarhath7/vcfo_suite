/**
 * LABOUR REGISTERS — the form catalogue.
 *
 * Each entry is a prescribed register or return, with the columns it prints in the order it
 * prints them. Everything here was read off filed client workbooks for Telangana, Karnataka,
 * Kerala and Haryana (September and October 2026) and off research into the central rules; no
 * entry has been checked against a gazette PDF or a state labour department's own form, so
 * every `verification.status` is `unverified` and the generator prints that on the document.
 *
 * Three corrections sit in this file that an earlier draft of the feature had wrong, and they
 * are the reason the catalogue is data rather than a hard-coded list:
 *
 *  - Kerala has no Form XIV register. The Kerala set is Form A and B for employment, Form BB
 *    for the service record and Form F for holidays and leave. "XIV" is a section heading in
 *    the Act, not a form.
 *  - Haryana's wage register is Form D, with deductions in Form E. Forms XIII and XIV are
 *    central Contract Labour forms, not Haryana's.
 *  - Form D under the Equal Remuneration Act 1976 stops on 20 November 2025. The Act was
 *    repealed by section 69(1) of the Code on Wages with effect from 21 November 2025 and the
 *    research found no successor register, so the form is kept for earlier periods only.
 */
import type { FormColumn, FormSpec } from './types';

/** A column, written short because the catalogue is mostly columns. */
function c(field: string, heading: string, ordinal?: number): FormColumn {
  return { field, heading, source: 'input', ordinal };
}
function m(field: string, heading: string, ordinal?: number): FormColumn {
  return { field, heading, source: 'master', ordinal };
}
function d(field: string, heading: string, ordinal?: number): FormColumn {
  return { field, heading, source: 'derived', ordinal };
}
function g(heading: string, ordinal?: number): FormColumn {
  return { field: 'attendanceGrid', heading, source: 'grid', ordinal };
}
function sig(heading: string, ordinal?: number): FormColumn {
  return { field: 'signature', heading, source: 'signature', ordinal };
}
const UNVERIFIED = {
  status: 'unverified' as const,
  open: ['signatory', 'seal', 'page initialling', 'exact column order'],
};

