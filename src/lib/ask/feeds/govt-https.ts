/** Node's normal trusted roots plus the missing intermediate(s). Verification stays on. */
const GOVT_CA = [...tls.rootCertificates, SECTIGO_OV_R36_PEM];

/** Responses larger than this are refused (a CBIC download is ~0.5 MB). */
const MAX_BYTES = 40 * 1024 * 1024;

export function govtGetText(url: string, timeoutMs = 30_000, redirectsLeft = 3): Promise<{ status: number; body: string }> {
  return new Promise((resolve, reject) => {
    const req = https.get(url, { headers: GOVT_FETCH_HEADERS, ca: GOVT_CA, timeout: timeoutMs }, (res) => {
      const status = res.statusCode ?? 0;
      if (status >= 300 && status < 400 && res.headers.location && redirectsLeft > 0) {
        res.resume();
        const next = new URL(res.headers.location, url);
        if (next.protocol !== 'https:') return reject(new Error('Refused a redirect away from HTTPS'));
        govtGetText(next.href, timeoutMs, redirectsLeft - 1).then(resolve, reject);
        return;
      }
      const chunks: Buffer[] = [];
      let size = 0;
      res.on('data', (chunk: Buffer) => {
        size += chunk.length;
        if (size > MAX_BYTES) {
          req.destroy(new Error('Response too large'));
          return;
        }
        chunks.push(chunk);
      });
      res.on('end', () => resolve({ status, body: Buffer.concat(chunks).toString('utf8') }));
      res.on('error', reject);
    });
    req.on('timeout', () => req.destroy(new Error(`Timed out after ${Math.round(timeoutMs / 1000)} s`)));
    req.on('error', reject);
  });
}
