/** Flip one byte at an offset, in a copy. */
function flip(pdf: Buffer, at: number): Buffer {
  const copy = Buffer.from(pdf);
  copy[at] = copy[at]! ^ 0x01;
  return copy;
}

describe('readPdfSignatures', () => {
  it('reads and verifies an RSA signature', () => {
    const [sig, ...rest] = readPdfSignatures(RSA);
    expect(rest).toHaveLength(0);
    expect(sig).toMatchObject({ index: 1, signerName: 'ASHA RAO', digestOk: true, signatureOk: true, expiredAtSigning: false, coversFile: true, error: null, digestAlgorithm: 'sha256' });
    expect(sig!.serial).toMatch(/^[0-9A-F]+$/);
    expect(new Date(sig!.validTo!).getTime()).toBeGreaterThan(new Date(sig!.validFrom!).getTime());
    expect(sig!.signingTime).toBeTruthy();
  });

  it('reads and verifies an EC signature', () => {
    expect(readPdfSignatures(EC)[0]).toMatchObject({ signerName: 'RAVI KUMAR', digestOk: true, signatureOk: true, expiredAtSigning: false });
  });

  it('reports a certificate that had expired when it signed, and still checks the bytes', () => {
    expect(readPdfSignatures(EXPIRED)[0]).toMatchObject({ signerName: 'OLD SIGNER', digestOk: true, signatureOk: true, expiredAtSigning: true });
  });

  it('fails the digest when a signed byte changes', () => {
    const [sig] = readPdfSignatures(flip(RSA, 12));
    expect(sig!.digestOk).toBe(false);
    expect(sig!.signatureOk).toBe(true);
  });

  it('fails the signature when the signature value changes', () => {
    // The RSA signature value ends the CMS; flip a hex digit inside it, before the zero padding.
    const text = RSA.toString('latin1');
    const gapEnd = text.lastIndexOf('>/M(D:');
    const hexEnd = text.slice(0, gapEnd).replace(/0+$/, '').length;
    const tampered = Buffer.from(RSA);
    tampered[hexEnd - 4] = tampered[hexEnd - 4] === 0x41 ? 0x42 : 0x41;
    const [sig] = readPdfSignatures(tampered);
    expect(sig!.digestOk).toBe(true);
    expect(sig!.signatureOk).toBe(false);
  });

  it('says when content was appended after the signature', () => {
    const appended = Buffer.concat([RSA, Buffer.from('4 0 obj\n<<>>\nendobj\n')]);
    const [sig] = readPdfSignatures(appended);
    expect(sig!.coversFile).toBe(false);
    expect(sig!.digestOk).toBe(true);
    expect(readPdfSignatures(Buffer.concat([RSA, Buffer.from('\n')]))[0]!.coversFile).toBe(true);
  });

  it('returns nothing for a PDF with no signature and never throws on junk', () => {
    expect(readPdfSignatures(Buffer.from('%PDF-1.4\nno signature here\n%%EOF'))).toEqual([]);
    const [bad] = readPdfSignatures(Buffer.from('%PDF /ByteRange [0 5 9999 9999] junk'));
    expect(bad).toMatchObject({ digestOk: false, signatureOk: false, error: 'bad_byte_range' });
    const [hexJunk] = readPdfSignatures(Buffer.from('/ByteRange [0 29 37 0] /Contents <zz12zz>'));
    expect(hexJunk!.signatureOk).toBe(false);
  });

  it('reads a signed incremental update, whose text hash equals the unsigned PDF', async () => {
    const [sig, ...rest] = readPdfSignatures(SIGNED_COPY);
    expect(rest).toHaveLength(0);
    expect(sig).toMatchObject({ signerName: 'RAVI KUMAR', digestOk: true, signatureOk: true, coversFile: true, expiredAtSigning: false });
    const unsigned = SIGNED_COPY.subarray(0, PORTAL_BYTES);
    expect(readPdfSignatures(unsigned)).toEqual([]);
    const [a, b] = await Promise.all([extractPdfText(unsigned), extractPdfText(SIGNED_COPY)]);
    expect(a.unreadable).toBe(false);
    expect(a.text).toContain('Acme Robotics Private Limited');
    expect(b.textHash).toBe(a.textHash);
  });

  it('states that the trust chain is not checked', () => {
    expect(TRUST_CHAIN_CHECKED).toBe(false);
  });
});
